#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Open the PnC or payload serial console in tio, matched by Pico USB serial.

macOS has no /dev/serial/by-id, and both Picos enumerate as "Pico 2W" with
changing /dev/cu.usbmodem* names, so tio cannot tell them apart on its own. This
script maps each board's USB serial number to its current port through ioreg,
regenerates ~/.config/tio/ports.conf, and then runs tio with that board's
profile (timestamped output, logging, color).

    uv run scripts/tio_serial.py pnc      # console for the PnC board
    uv run scripts/tio_serial.py payload  # console for the payload board
    uv run scripts/tio_serial.py both     # both in a tmux session
    uv run scripts/tio_serial.py status   # show the current mapping only

Logs are appended under logs/ in ISO 8601 timestamped lines:
    grep -a "SD" logs/pnc.log
    tail -f logs/payload.log

tio reconnects to the same path on its own. If a board is moved to a different
USB port its /dev name changes; rerun the same command to re-resolve it.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LOG_DIR = REPO_ROOT / "logs"
CONFIG_DIR = Path(
    os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config"
) / "tio"
PORTS_FILE = CONFIG_DIR / "ports.conf"
TMUX_SESSION = "ascend-serial"

# USB serial numbers of the two Pico 2W boards on the bench (ioreg
# "USB Serial Number"). Replace these if a board is swapped; the `list` target
# prints every attached serial device with its port if the mapping is unclear.
BOARDS = {
    "pnc": "D162021C0D4C998A",
    "payload": "348184284261CE9B",
}
COLORS = {"pnc": 6, "payload": 3}

ENTRY_RE = re.compile(r"^(?P<indent>[ |]*)\+-o ")
PROPERTY_RE = re.compile(
    r'^[ |]*"(?P<key>USB Serial Number|kUSBSerialNumberString|IOCalloutDevice)"'
    r'\s*=\s*"(?P<value>[^"]+)"'
)


@dataclass
class Device:
    serial: str | None
    port: str | None
    name: str


def ioreg_lines() -> list[str]:
    try:
        output = subprocess.run(
            ["ioreg", "-p", "IOService", "-w0", "-l"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        raise SystemExit(f"Cannot read USB device tree with ioreg: {exc}") from exc
    return output.splitlines()


def underlying_usb_devices(lines: list[str]) -> list[Device]:
    """Return every USB device with its serial number and callout port.

    ioreg prints a depth-indented tree, so descendants (the CDC ACM serial
    client) carry a deeper indent than the USB device that owns the serial
    number. Frames track that ancestry.
    """
    frames: list[dict] = []
    devices: list[Device] = []
    for line in lines:
        entry = ENTRY_RE.match(line)
        if entry:
            column = len(entry.group("indent"))
            while frames and frames[-1]["column"] >= column:
                frames.pop()
            label = line.split("+-o ", 1)[1].split("  <class")[0].strip()
            frames.append({"column": column, "label": label, "serial": None})
            continue

        prop = PROPERTY_RE.match(line)
        if not prop or not frames:
            continue
        key, value = prop.group("key"), prop.group("value")
        if key == "IOCalloutDevice":
            # The nearest frame with a serial number is the interface, which
            # inherits it from the USB device above it; take the topmost so the
            # device name is reported rather than "IOUSBHostInterface".
            owner = next((f for f in frames if f.get("serial")), None)
            if owner:
                devices.append(Device(owner["serial"], value, owner["label"]))
        else:
            frames[-1]["serial"] = value
    return devices


def current_ports() -> dict[str, str]:
    """Map board name to its current /dev/cu.* port."""
    devices = {d.serial: d for d in underlying_usb_devices(ioreg_lines())}
    ports: dict[str, str] = {}
    for board, serial in BOARDS.items():
        device = devices.get(serial)
        if device and device.port and device.port.startswith("/dev/cu."):
            ports[board] = device.port
    return ports


def write_ports_file(ports: dict[str, str]) -> None:
    """Regenerate the tio profile include with the current device paths."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by scripts/tio_serial.py; do not edit.", ""]
    for board in BOARDS:
        port = ports.get(board)
        if not port:
            continue
        lines += [
            f"[{board}]",
            f"device = {port}",
            f"color = {COLORS[board]}",
            f"log-file = {LOG_DIR / (board + '.log')}",
            "",
        ]
    with tempfile.NamedTemporaryFile(
        "w", dir=CONFIG_DIR, prefix=".ports.", delete=False
    ) as handle:
        handle.write("\n".join(lines))
        temporary = Path(handle.name)
    temporary.replace(PORTS_FILE)


def describe(ports: dict[str, str]) -> str:
    rows = []
    for board, serial in BOARDS.items():
        port = ports.get(board, "not connected")
        rows.append(f"  {board:<8} {port:<22} usb serial {serial}")
    return "\n".join(rows)


def list_devices() -> int:
    devices = underlying_usb_devices(ioreg_lines())
    if not devices:
        print("No USB serial devices found.")
        return 1
    for device in sorted(devices, key=lambda d: d.port or ""):
        board = next((b for b, s in BOARDS.items() if s == device.serial), "?")
        print(
            f"{device.port or 'no port':<24} {board:<8} "
            f"{device.name:<20} {device.serial}"
        )
    return 0


def start_both(ports: dict[str, str]) -> int:
    if not shutil.which("tmux"):
        print("tmux is not installed; run the boards in separate terminals.",
              file=sys.stderr)
        return 1
    if not sys.stdout.isatty():
        print("'both' needs an interactive terminal to attach the tmux session.",
              file=sys.stderr)
        return 1

    missing = [board for board in BOARDS if board not in ports]
    if missing:
        print(f"Not connected: {', '.join(missing)}", file=sys.stderr)
        return 1

    exists = subprocess.run(
        ["tmux", "has-session", "-t", TMUX_SESSION],
        capture_output=True,
        check=False,
    ).returncode == 0
    if exists:
        print(f"Attaching to existing tmux session {TMUX_SESSION}.", file=sys.stderr)
        os.execvp("tmux", ["tmux", "attach-session", "-t", TMUX_SESSION])

    subprocess.run(
        ["tmux", "new-session", "-d", "-s", TMUX_SESSION, "-n", "pnc",
         "-c", str(REPO_ROOT), "tio pnc"],
        check=True,
    )
    subprocess.run(
        ["tmux", "new-window", "-t", TMUX_SESSION, "-n", "payload",
         "-c", str(REPO_ROOT), "tio payload"],
        check=True,
    )
    subprocess.run(["tmux", "select-window", "-t", f"{TMUX_SESSION}:pnc"], check=True)
    os.execvp("tmux", ["tmux", "attach-session", "-t", TMUX_SESSION])
    return 0  # unreachable


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Open the ASCEND PnC or payload console in tio by USB serial."
    )
    parser.add_argument("target", choices=[*BOARDS, "both", "status", "list"])
    parser.add_argument(
        "--print", action="store_true", help="print the resolved tio command instead of running it"
    )
    args = parser.parse_args()

    if args.target == "list":
        return list_devices()

    ports = current_ports()
    write_ports_file(ports)

    if args.target == "status":
        print(describe(ports))
        return 0 if len(ports) == len(BOARDS) else 1

    if args.target == "both":
        return start_both(ports)

    if args.target not in ports:
        print(
            f"{args.target} board (usb serial {BOARDS[args.target]}) is not connected.\n"
            f"Attached devices:\n{describe(ports)}",
            file=sys.stderr,
        )
        return 1

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    print(describe(ports), file=sys.stderr)
    print(f"Logging to {LOG_DIR / (args.target + '.log')}", file=sys.stderr)
    if args.print:
        print(f"tio {args.target}")
        return 0
    os.execvp("tio", ["tio", args.target])
    return 0  # unreachable


if __name__ == "__main__":
    sys.exit(main())
